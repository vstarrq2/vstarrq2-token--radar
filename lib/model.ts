/** A second, different action for the same protocol: a second chain, or a second position. */
function secondActionFor(p: SnapshotProtocol, capital: number, chain: string): string {
  const second = secondChainOf(p);
  if (second !== null) return `Repeat the position on ${second} with $20 of USDC so the activity spans two chains.`;
  const c = (p.category ?? '').toLowerCase();
  const name = p.name;
  if (c.includes('lending') || c.includes('cdp') || c.includes('collateral')) return `Borrow $20 against the supply on ${name}, then repay it the same week to register borrower activity.`;
  if (c.includes('dex') || c.includes('yield') || c.includes('farm')) return `Add $20 to a second pool on ${name} so the wallet holds two positions, not one.`;
  if (c.includes('bridge')) return `Bridge $20 back the other way through ${name} once, so the wallet shows both directions.`;
  if (c.includes('staking') || c.includes('restak')) return `Restake the receipt once through ${name} so the wallet holds the receipt and the restaked position.`;
  if (c.includes('perpetual') || c.includes('derivative') || c.includes('basis trading')) return `Close the hedge on ${name} and open a fresh one, so the account shows two settled trades.`;
  if (c.includes('prediction')) return `Settle the first market on ${name} and place a second one.`;
  if (c.includes('curator') || c.includes('allocator')) return `Deposit $20 into a second ${name} vault so the wallet holds two vault shares.`;
  if (c.includes('stable')) return `Mint a second stable position of $20 through ${name} and hold it beside the first.`;
  return `Make a second deposit of $20 into ${name} on ${chain} so the wallet shows repeat activity, not a single transaction.`;
}

/** The weekly qualifying action, flavoured by the protocol's category. */
function weeklyActionFor(p: SnapshotProtocol): string {
  const c = (p.category ?? '').toLowerCase();
  if (c.includes('lending') || c.includes('cdp') || c.includes('collateral')) return 'Supply or borrow a small amount each week so the wallet stays active.';
  if (c.includes('dex') || c.includes('yield') || c.includes('farm')) return 'Swap or add a little liquidity each week so the wallet shows trader activity too.';
  if (c.includes('bridge')) return 'Bridge a small amount each week so the wallet keeps moving funds.';
  if (c.includes('staking') || c.includes('restak')) return 'Claim or compound the staking rewards each week.';
  if (c.includes('perpetual') || c.includes('derivative') || c.includes('basis trading')) return 'Open or close one small position each week.';
  if (c.includes('prediction')) return 'Place or settle one market each week.';
  if (c.includes('curator') || c.includes('allocator')) return 'Top up a vault by $20 once a week.';
  return 'Make one qualifying action each week, such as a deposit, a borrow, a swap or a vote.';
}

/**
 * A protocol's farm plan: six steps, each an action with a cost and a time. The plan is derived
 * from the protocol's own record (category, chains, TVL, age), never from a hand-written list of
 * names. The dashboard regenerates the same plan in the page from the same derivation.
 */
export function farmSteps(p: SnapshotProtocol, age: number | null): FarmStep[] {
  const chain = chainOf(p);
  const capital = capitalFor(p);
  const hold = holdDaysFor(age);
  return [
    {
      text: `Use a fresh wallet that holds only the funds you plan to farm, and keep its seed phrase offline.`,
      cost: 'under $3 of gas for the first transaction',
      time: '5 minutes',
    },
    {
      text: actionFor(p, capital, chain),
      cost: `$${capital} of capital and about $${capital >= 150 ? 8 : 4} of gas`,
      time: '15 minutes to set up',
    },
    {
      text: secondActionFor(p, capital, chain),
      cost: 'about $4 of gas and $20 of capital',
      time: '10 minutes',
    },
    {
      text: weeklyActionFor(p),
      cost: 'about $2 of gas a week',
      time: '10 minutes a week',
    },
    {
      text: `Hold the position for at least ${hold} days so the activity is counted in more than one snapshot.`,
      cost: `the $${capital} stays in the position`,
      time: `${hold} days`,
    },
    {
      text: `Before you withdraw, open the protocol's own points or rewards page and claim only from the link it publishes, then write the wallet, the dates and every transaction in a farm log.`,
      cost: 'no fee to check, and never pay to claim',
      time: '10 minutes',
    },
  ];
}

/** The live-token protocols, by market cap, for the dashboard's Live token view. */
export function liveRows(snapshot: Snapshot): LiveRow[] {
  return snapshot.protocols
    .filter((p) => !isPreToken(p) && p.category !== 'CEX')
    .sort((a, b) => (b.mcap_usd ?? 0) - (a.mcap_usd ?? 0) || b.tvl_usd - a.tvl_usd)
    .slice(0, LIVE_ROWS)
    .map((p) => ({
      slug: p.slug,
      name: p.name,
      category: p.category,
      chains: p.chains,
      tvl_usd: p.tvl_usd,
      mcap_usd: p.mcap_usd,
      change_7d: p.change_7d,
      mcap_tvl_ratio: p.mcap_usd !== null && p.tvl_usd > 0 ? round4(p.mcap_usd / p.tvl_usd) : null,
    }));
}

