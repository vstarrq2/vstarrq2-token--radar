// The token radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds
// every rankable pre-token protocol below the watchlist floor: the early rows the radar exists to
// find. A protocol is pre-token when its index entry records no token (no market cap, no
// CoinGecko id, no symbol). The snapshot's live-token protocols are kept apart in the Live view
// and shown at the market's own values, never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures, and the multiple it is priced at
// is the snapshot's own market, not a constant somebody typed in:
//
//   comp     = median(mcap_usd / tvl_usd) over the tokenized protocols at or above the
//              watchlist floor ($50M) that record a market cap — the multiple live tokens
//              actually trade at, computed from this snapshot at run time
//   base     = tvl_usd x comp
//   growth   = clamp(change_7d, -60, 120) per cent
//   growthMult   = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity     = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   breadth      = 1 + min(chains - 1, 3) x 0.05           (a protocol live on more chains
//                                                          reaches more users for its token)
//   implied  = max(1, round(base x growthMult x maturity x breadth))
//
// No protocol name is ever special-cased: the same function scores every row. The dashboard
// states the formula and the comp multiple it ran with, so a reader can check any row by hand.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

